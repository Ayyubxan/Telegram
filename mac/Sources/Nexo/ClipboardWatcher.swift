import AppKit
import UniformTypeIdentifiers

final class ClipboardWatcher {
    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    var onCopy: ((String) -> Void)?
    var onImage: ((Data, String) -> Void)?

    private static let jpeg = NSPasteboard.PasteboardType("public.jpeg")

    // Parol menejerlari (1Password, Bitwarden...) shu turlar bilan belgilaydi — ularni yubormaymiz.
    private static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init() { lastChange = pasteboard.changeCount }

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChange else { return }
        lastChange = count
        if let types = pasteboard.types, !Self.skipTypes.isDisjoint(with: types) { return }
        // Matn birinchi: Finder'da fayl nusxalanganda ham nomi matn sifatida keladi
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            onCopy?(text)
        } else if let onImage, let (data, mime) = imageData() {
            onImage(data, mime)
        }
    }

    /// Clipboard'dagi rasm: PNG/JPEG bo'lsa o'zi, TIFF bo'lsa PNG'ga, limitdan katta bo'lsa JPEG'ga o'giriladi.
    private func imageData() -> (Data, String)? {
        if let jpg = pasteboard.data(forType: Self.jpeg), jpg.count <= SyncEngine.maxFileBytes {
            return (jpg, "image/jpeg")
        }
        let png = pasteboard.data(forType: .png)
        if let png, png.count <= SyncEngine.maxFileBytes { return (png, "image/png") }
        guard let raw = png ?? pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: raw) else { return nil }
        if png == nil, let converted = rep.representation(using: .png, properties: [:]),
           converted.count <= SyncEngine.maxFileBytes {
            return (converted, "image/png")
        }
        guard let jpg = rep.representation(using: .jpeg, properties: [.compressionFactor: 0.85]),
              jpg.count <= SyncEngine.maxFileBytes else { return nil }
        return (jpg, "image/jpeg")
    }

    /// Boshqa qurilmadan kelgan matnni yozadi — qayta yuborilmaydi.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
    }

    /// Boshqa qurilmadan kelgan rasmni yozadi: asl format + TIFF (eski ilovalar uchun).
    @discardableResult
    func writeImage(_ data: Data, mime: String?) -> Bool {
        guard let image = NSImage(data: data) else { return false }
        let item = NSPasteboardItem()
        if let id = mime.flatMap({ UTType(mimeType: $0) })?.identifier {
            item.setData(data, forType: NSPasteboard.PasteboardType(id))
        }
        if let tiff = image.tiffRepresentation { item.setData(tiff, forType: .tiff) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        lastChange = pasteboard.changeCount
        return true
    }
}
